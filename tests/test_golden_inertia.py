"""Regression: edtsim must reproduce what the ORIGINAL notebook functions produced.

Fixture generated by scripts/generate_golden_inertia.py (see provenance block in the JSON).
"""
import json
from pathlib import Path

import numpy as np
import pytest

from edtsim.core import (BusParams, PointMassParams, SpoolParams, TetherParams,
                         euler_zyx_to_R, rotation_matrix_from_a_to_b)
from edtsim.inertia import (annular_cylinder_inertia_about_com, box_inertia_about_com,
                            inertia_body_to_inertial, inertia_from_particles,
                            moi_config_1_coiled, moi_config_2_extended_on_minus_z,
                            parallel_axis_shift, sample_point_in_annular_cylinder,
                            slender_rod_inertia_about_com)

G = json.loads((Path(__file__).parent / "fixtures" / "golden_inertia.json").read_text())


def close(actual, desired, rtol=1e-12, atol=None):
    """Elementwise ``rtol`` plus an absolute floor tied to the LARGEST entry of ``desired``.

    Rounding error scales with the biggest numbers involved, not with each element. A small
    element of a tensor with a large dynamic range (e.g. Izz ~ 0.005 next to Ixx ~ 500 for a long
    tether) is computed by cancelling large terms and can legitimately differ from the reference
    by ~1e-14 on another CPU/BLAS. A real formula error would be many orders of magnitude larger.
    """
    desired = np.asarray(desired, dtype=float)
    if atol is None:
        atol = 1e-12 * float(np.max(np.abs(desired)))
    np.testing.assert_allclose(actual, desired, rtol=rtol, atol=atol)


def A(x):
    return np.asarray(x, dtype=float)


@pytest.mark.parametrize("name", list(G["satellite_cases"]))
def test_satellite_configs_match_legacy(name):
    case = G["satellite_cases"][name]
    c = case["inputs"]
    bus = BusParams(**c["bus"])
    spool = SpoolParams(**c["spool"])
    if c["end_mode"] == "known":
        r_end = A(c["r_end_B"])
    else:
        r_end = sample_point_in_annular_cylinder(spool.r_i, spool.r_o, spool.h, spool.axis_s_B,
                                                 spool.com_B, np.random.default_rng(c["seed"]))
    close(r_end, A(case["r_end_B"]))
    close(moi_config_1_coiled(bus, spool, c["m_end_stowed"], r_end), A(case["I1"]))

    I2, r_p, r_a = moi_config_2_extended_on_minus_z(
        bus, TetherParams(**c["tether"]), PointMassParams(c["m_end_deployed"]))
    close(I2, A(case["I2"]))
    close(r_p, A(case["r_p_B0"]))
    close(r_a, A(case["r_a_B"]))


def test_primitives_match_legacy():
    P = G["primitives"]
    for e in P["parallel_axis"]:
        close(parallel_axis_shift(e["m"], e["r"]), A(e["I"]))
    for e in P["box"]:
        close(box_inertia_about_com(e["m"], e["a"], e["b"], e["c"]), A(e["I"]))
    for e in P["annulus"]:
        close(
            annular_cylinder_inertia_about_com(e["m"], e["r_i"], e["r_o"], e["h"], e["axis"]), A(e["I"]))
    for e in P["rod"]:
        close(slender_rod_inertia_about_com(e["m"], e["L"], e["axis"]), A(e["I"]))


def test_euler_and_body_to_inertial_match_legacy():
    for e in G["euler_zyx"]:
        R = euler_zyx_to_R(e["roll"], e["pitch"], e["yaw"])
        close(R, A(e["R"]))
        close(inertia_body_to_inertial(box_inertia_about_com(4.0, 0.1, 0.1, 0.3), R),
                                   A(e["I_I"]))


def test_rotation_a_to_b_matches_legacy():
    for e in G["rotation_a_to_b"]:
        close(rotation_matrix_from_a_to_b(e["a"], e["b"]), A(e["R"]))


def test_particle_inertia_matches_legacy():
    p = G["particles"]
    close(inertia_from_particles(A(p["r"]), A(p["m"]), A(p["ref"])), A(p["I"]),
                               rtol=1e-12, atol=1e-12)
